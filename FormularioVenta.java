    private void btnAgregarVentaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarVentaActionPerformed
        // TODO add your handling code here:
        try {
    if (indice >= ventas.length) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "Ya registraste las 5 ventas."
        );
        return;
    }

    double monto = Double.parseDouble(txtVenta.getText());

    if (monto < 0) {
        javax.swing.JOptionPane.showMessageDialog(
            this, "El monto no puede ser negativo."
        );
        return;
    }

    ventas[indice] = monto;
    indice++;

    txtVenta.setText("");

    javax.swing.JOptionPane.showMessageDialog(
        this, "Venta agregada correctamente."
    );

} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingresa un monto numérico válido."
    );
}
        
        
        
    }//GEN-LAST:event_btnAgregarVentaActionPerformed

    private void btnGenerarReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGenerarReporteActionPerformed
        // TODO add your handling code here:
    
double total = 0;
    int mayores500 = 0;

    for(int i = 0; i < ventas.length; i++){

        total += ventas[i];

        if(ventas[i] > 500){
            mayores500++;
        }
    }

    try{

        // Crear carpeta temp si no existe
        java.io.File carpeta = new java.io.File("temp");

        if(!carpeta.exists()){
            carpeta.mkdirs();
        }

        // Crear archivo
        java.io.FileWriter fw =
                new java.io.FileWriter("temp/Sasha_reporte_ventas.txt");

        fw.write("Reporte de Ventas\n");
        fw.write("Total Vendido: Q" + total + "\n");
        fw.write("Ventas superiores a Q500: " + mayores500);

        fw.close();

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Reporte creado correctamente"
        );

    }catch(Exception e){

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Error: " + e.getMessage()
        );
    }

    }//GEN-LAST:event_btnGenerarReporteActionPerformed

