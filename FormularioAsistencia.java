    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        // TODO add your handling code here:
        
        if (indice >= asistentes.length) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ya registraste los 5 asistentes."
    );
    return;
}

String nombre = txtNombre.getText().trim();

if (nombre.isEmpty()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Ingresa el nombre del asistente."
    );
    return;
}

asistentes[indice] = nombre;
indice++;

txtLista.append(
    indice + ". " + nombre + "\n"
);

txtNombre.setText("");

javax.swing.JOptionPane.showMessageDialog(
    this, "Asistente registrado correctamente."
);
    }//GEN-LAST:event_btnRegistrarActionPerformed

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExportarActionPerformed
        // TODO add your handling code here:
        if (indice < asistentes.length) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Debes registrar los 5 asistentes primero."
    );
    return;
}

java.io.File carpeta = new java.io.File("temp");

if (!carpeta.exists() && !carpeta.mkdirs()) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "No se pudo crear la carpeta temp."
    );
    return;
}

java.io.File archivo = new java.io.File(
    carpeta, "anderson_asistencia.txt"
);

try (java.io.PrintWriter escritor =
        new java.io.PrintWriter(
            new java.io.FileWriter(archivo))) {

    escritor.println("Lista de Asistencia");

    for (int i = 0; i < asistentes.length; i++) {
        escritor.println(
            (i + 1) + ". " + asistentes[i]
        );
    }

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Lista exportada correctamente.\nGuardada en:\n"
        + archivo.getAbsolutePath()
    );

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al exportar: " + e.getMessage()
    );
}
    }//GEN-LAST:event_btnExportarActionPerformed

