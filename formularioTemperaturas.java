    private void btnCargarDatosActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCargarDatosActionPerformed
        // TODO add your handling code here:
      try {
    java.io.File archivo = new java.io.File(
        "C:\\Users\\balde\\OneDrive\\Documentos\\NetBeansProjects\\JavaFundamentals\\temp\\temperaturas.txt..txt"
    );

    System.out.println("¿Existe el archivo?: " + archivo.exists());
    System.out.println("¿Es un archivo?: " + archivo.isFile());
    System.out.println("Ruta: " + archivo.getAbsolutePath());

    if (!archivo.exists() || !archivo.isFile()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No se encontró temperaturas.txt.\n"
            + archivo.getAbsolutePath()
        );
        return;
    }

    indice = 0;

    try (java.util.Scanner sc =
            new java.util.Scanner(archivo, "UTF-8")) {

        while (sc.hasNextLine()) {
            String linea = sc.nextLine().trim();

            if (linea.isEmpty()) {
                continue;
            }

            if (indice >= temperaturas.length) {
                javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "El archivo tiene demasiadas temperaturas."
                );
                return;
            }

            temperaturas[indice] =
                Double.parseDouble(linea);

            indice++;
        }
    }

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Datos cargados correctamente: "
        + indice + " temperaturas."
    );

} catch (java.io.IOException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Error al leer: " + e.getMessage()
    );
} catch (NumberFormatException e) {
    javax.swing.JOptionPane.showMessageDialog(
        this, "Hay una temperatura que no es numérica."
    );
}
    }//GEN-LAST:event_btnCargarDatosActionPerformed

    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        double suma = 0;
    int calidos = 0;
    int frescos = 0;

    for(int i = 0; i < temperaturas.length; i++){

        suma += temperaturas[i];

        if(temperaturas[i] >= 25){

            calidos++;

        }else{

            frescos++;
        }
    }

    double promedio =
            suma / temperaturas.length;

    txtResultado.setText(
            "ANALISIS CLIMATICO\n\n" +
            "----------------------\n\n" +
            "Promedio de Temperatura: "
            + promedio +
            "\n\nDias Calidos (>=25): "
            + calidos +
            "\n\nDias Frescos (<25): "
            + frescos
    );

    }//GEN-LAST:event_btnCalcularActionPerformed

