     public void cargarDiscos(){

        try{

            java.io.File archivo =
            new java.io.File(
            "C:\\Users\\balde\\OneDrive\\Documentos\\NetBeansProjects\\JavaFundamentals\\temp\\disco.scv.txt");

            java.util.Scanner sc =
            new java.util.Scanner(archivo);

            int i = 0;

            while(sc.hasNextLine()){

                String datos[] =
                sc.nextLine().split(",");

                titulos[i] = datos[0];
                anios[i] = Integer.parseInt(datos[1]);

                i++;
            }

            sc.close();

        }catch(Exception e){

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    e.getMessage());
        }
    }

