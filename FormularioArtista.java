    private void btnCrearCancionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearCancionActionPerformed
        // TODO add your handling code here:
        Cancion c = new Cancion();

    c.titulo = txtTitulo.getText();
    c.nombreArtista = txtNombre.getText();
    c.duracionSegundos =
            Integer.parseInt(txtDuracion.getText());
    c.genero = txtGenero.getText();

    txtResultado.append(
            "CANCION\n" +
            "Titulo: " + c.titulo +
            "\nArtista: " + c.nombreArtista +
            "\nDuracion: " + c.duracionSegundos +
            "\nGenero: " + c.genero +
            "\n\n"
    );
    }//GEN-LAST:event_btnCrearCancionActionPerformed

    private void btnCrearArtistaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCrearArtistaActionPerformed
        // TODO add your handling code here:
      Artista a = new Artista();

    a.nombre = txtNombre.getText();
    a.paisOrigen = txtPais.getText();
    a.oyentesMensuales =
            Integer.parseInt(txtOyentes.getText());

    txtResultado.append(
            "ARTISTA\n" +
            "Nombre: " + a.nombre +
            "\nPais: " + a.paisOrigen +
            "\nOyentes Mensuales: "
            + a.oyentesMensuales +
            "\n\n"
    );
    }//GEN-LAST:event_btnCrearArtistaActionPerformed

